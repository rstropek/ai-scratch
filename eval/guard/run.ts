// Runs the labelled kid messages (cases.ts) through the kids-protection guard against the real Jev model
// and writes docs/kids-protection.md, the record of what was tested. Costs fractions of a cent.
//   npm run eval:guard
import fs from 'node:fs';
import {
  BLOCK_SCREENING,
  CHAT_SCREENING,
  FIXED_ANSWERS,
  type GuardResult,
  type QuestionId,
  type Screening,
  screen,
  THRESHOLDS,
} from '../../src/server/guard.ts';
import { MAX_ANSWER_CHARS, MAX_STEPS_PER_TURN } from '../../src/server/output-guard.ts';
import { BLOCK_CASES, CASES, type Expected, type GuardCase } from './cases.ts';

const REPORT = 'docs/kids-protection.md';
const CONCURRENCY = 4;

const apiKey = process.env.JEV_API_KEY;
if (!apiKey) throw new Error('JEV_API_KEY missing (.env)');
const model = process.env.JEV_MODEL?.trim() || 'jev-1.13.0';

const pool = async <T, R>(items: T[], run: (item: T) => Promise<R>): Promise<R[]> => {
  const results: R[] = new Array(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      results[i] = await run(items[i] as T);
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  return results;
};

interface Row extends GuardCase {
  actual: Expected;
  result: GuardResult;
}

const run = (cases: GuardCase[], screening: Screening): Promise<Row[]> =>
  pool(cases, async (c) => {
    const result = await screen(c.text, c.previous, { apiKey, model }, screening);
    if (result.error) throw new Error(`Jev failed for "${c.text}": ${result.error}`);
    return { ...c, actual: result.category === 'too_long' ? 'pass' : (result.category ?? 'pass'), result };
  });
const chatRows = await run(CASES, CHAT_SCREENING);
const blockRows = await run(BLOCK_CASES, BLOCK_SCREENING);
const rows = [...chatRows, ...blockRows];

// --- report -------------------------------------------------------------------------------------------

const CATEGORIES: Expected[] = ['distress', 'inappropriate', 'personal_data', 'misuse', 'pass'];
const TITLES: Record<Expected, string> = {
  distress: 'Distress: personal, emotional or medical help',
  inappropriate: 'Inappropriate: insults, adult content, bullying real people',
  personal_data: 'Personal data',
  misuse: 'Misuse of the app: flooding and jailbreaks',
  pass: 'Harmless messages (must not be blocked)',
};

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)} %` : '–');
const esc = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
/** the questions that fired, else the highest one */
const evidence = (r: GuardResult) => {
  const entries = Object.entries(r.nouls) as [QuestionId, number][];
  const fired = entries.filter(([id, p]) => p >= THRESHOLDS[id].threshold);
  const shown = fired.length ? fired : entries.sort((a, b) => b[1] - a[1]).slice(0, 1);
  return shown.map(([id, p]) => `${id} ${p.toFixed(2)}`).join(', ');
};

const correct = rows.filter((r) => r.actual === r.expected).length;
const versions = [...new Set(rows.map((r) => r.result.model))].join(', ');
const misses = rows.filter((r) => r.actual !== r.expected);
const falseBlocks = rows.filter((r) => r.expected === 'pass' && r.actual !== 'pass').length;

/** the summary table and one table of cases per category */
const results = (set: Row[], heading: string) => {
  const summary = CATEGORIES.map((cat) => {
    const expected = set.filter((r) => r.expected === cat);
    const hits = expected.filter((r) => r.actual === cat).length;
    const flagged = set.filter((r) => r.actual === cat);
    const precision = cat === 'pass' ? '' : pct(flagged.filter((r) => r.expected === cat).length, flagged.length);
    return `| ${cat} | ${expected.length} | ${hits} | ${pct(hits, expected.length)} | ${precision} |`;
  });
  const sections = CATEGORIES.map((cat) => {
    const lines = set
      .filter((r) => r.expected === cat)
      .map(
        (r) =>
          `| ${r.actual === r.expected ? '✅' : '❌'} | ${esc(r.text)}${r.previous ? ` *(answering: „${esc(r.previous)}“)*` : ''} | ${r.actual} | ${evidence(r.result)} | ${r.note ?? ''} |`,
      );
    return lines.length
      ? [
          `${heading} ${TITLES[cat]}`,
          '',
          '| | Message | Result | Probability | Note |',
          '|---|---|---|---|---|',
          ...lines,
        ].join('\n')
      : '';
  });
  return [
    '| Expected | Cases | Recognised | Recall | Precision |',
    '|---|---|---|---|---|',
    ...summary,
    '',
    sections.filter(Boolean).join('\n\n'),
  ].join('\n');
};

const thresholdRows = Object.entries(THRESHOLDS).map(
  ([id, { category, threshold }]) => `| ${id} | ${category} | ${threshold} |`,
);
const answerRows = Object.entries(FIXED_ANSWERS).map(([cat, text]) => `| ${cat} | ${text} |`);

const report = `# Kids protection

What protects the kids (10–14) who chat with the KI-Helfer, and what was tested.
Generated by \`npm run eval:guard\` (eval/guard/run.ts); do not edit by hand.

**Last run:** ${new Date().toISOString().slice(0, 10)} · **Classifier:** TypeSafe ${versions} · **Cases:** ${rows.length} · **Correct:** ${correct} (${pct(correct, rows.length)}) · **Harmless messages blocked:** ${falseBlocks}

## How it works

- **Supervision first.** The kids work in a room with adults. The guard does not replace them; it keeps the
  assistant out of conversations it should not have and points kids to the adults when they need help.
- **Every new kid message is screened** by TypeSafe's Jev, a classifier that answers yes/no questions with a
  probability (src/server/guard.ts). It sees the message and the assistant's previous answer, so a short
  reply like "1000" is read in context.
- **A flagged message never reaches the AI model (Claude).** The kid gets a fixed answer, and the message and
  that answer are also left out of later model input.
- **The categories are checked in a fixed order;** the first one that fires wins, so a kid in distress is
  always sent to an adult, even if the message also contains an insult.
- **If Jev is unreachable** (3 s timeout), the message goes through (fail open): the event must not stop
  because of a third party, Claude refuses harmful requests on its own, and adults are present. Each
  outage is logged and counted in \`/api/stats\`.
- **Logging:** every screening goes to \`logs/guard.jsonl\` with the probabilities. Messages with personal
  data are stored as a placeholder.

### Fixed answers

| Category | Answer |
|---|---|
${answerRows.join('\n')}

### Questions and thresholds

A question fires at or above its threshold. Distress has a lower threshold: sending a kid to an adult once
too often costs little.

| Question | Category | Threshold |
|---|---|---|
${thresholdRows.join('\n')}

### Output limits

The answers are bounded as well, so a kid cannot provoke an endless answer
(src/server/output-guard.ts, covered by tests in src/server/app.test.ts):

- **Per AI call:** at most 16,000 output tokens, thinking and tool input included. That is far above
  real calls (largest measured: about 7,000).
- **Visible text per answer:** at most ${MAX_ANSWER_CHARS.toLocaleString('en')} characters. Real answers stay below 1,200. Longer text is cut at a
  word boundary with a note, and the AI call is stopped.
- **AI calls per turn:** at most ${MAX_STEPS_PER_TURN}. Real turns take 2–10. After that, the turn ends with a short
  message.
- **Kid messages:** at most 2,000 characters. The "frage KI" block keeps the last 3,000 characters of its text.

## Results: chat messages

${results(chatRows, '###')}

## Results: the "frage KI" block

A kid's own program (usually a chatbot) sends a text to the AI with the "frage KI" block
(src/server/ask.ts). Jev screens it with the same questions and thresholds, but with a description of the
block instead of the chat, and four questions reworded: giving the chatbot a role ("Du bist ein Pirat"),
playful teasing in that role and a sad character are fine here. Only the last 3,000 characters of the text
are screened and sent to the model, as a sliding window over a chatbot's growing conversation.

${results(blockRows, '###')}

## Known limits

- **Language:** Jev reads English best; German works with somewhat lower accuracy. The cases are German,
  with typos, slang and emojis, as kids write.
- **The cases are written by us,** not collected from real kids. Real messages from the event
  (\`logs/guard.jsonl\`) are the next test set.
- **Persistence:** a kid who rephrases long enough may get past the guard. Claude's own safety rules and
  the adults in the room are the next layers.
- **The AI's answers are not screened.** Claude is instructed for kids, and a flagged message never
  reaches it.
`;

fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync(REPORT, report);

console.log(`${correct}/${rows.length} correct, ${falseBlocks} harmless blocked → ${REPORT}`);
for (const r of misses) console.log(`  ✗ expected ${r.expected}, got ${r.actual}: ${r.text}  [${evidence(r.result)}]`);
